create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.market_candles (
  symbol text not null,
  interval text not null,
  candle_time timestamptz not null,
  open numeric(24,10) not null,
  high numeric(24,10) not null,
  low numeric(24,10) not null,
  close numeric(24,10) not null,
  volume numeric(28,8),
  source text not null default 'twelve_data',
  is_complete boolean not null default true,
  ingested_at timestamptz not null default now(),
  primary key (symbol, interval, candle_time),
  constraint market_candles_ohlc_check check (
    high >= greatest(open, close, low)
    and low <= least(open, close, high)
  )
);

create index if not exists market_candles_lookup_idx
  on public.market_candles (symbol, interval, candle_time desc);

create table if not exists public.ingestion_state (
  symbol text not null,
  interval text not null,
  status text not null default 'not_started'
    check (status in ('not_started','queued','downloading','syncing','complete','paused','error')),
  earliest_available timestamptz,
  latest_stored timestamptz,
  oldest_stored timestamptz,
  next_end_time timestamptz,
  rows_processed bigint not null default 0,
  rows_in_database bigint not null default 0,
  estimated_total bigint,
  batches_completed integer not null default 0,
  progress_percent numeric(7,3) not null default 0,
  last_success_at timestamptz,
  last_error text,
  updated_at timestamptz not null default now(),
  primary key (symbol, interval)
);

drop trigger if exists ingestion_state_updated_at on public.ingestion_state;
create trigger ingestion_state_updated_at
before update on public.ingestion_state
for each row execute function public.set_updated_at();

