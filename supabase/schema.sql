-- Atomically claim one queued job. Useful if Railway is later scaled to more workers.
create or replace function public.claim_next_ingestion_job(p_worker_id text)
returns setof public.ingestion_jobs
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  select id into v_id
  from public.ingestion_jobs
  where status = 'queued'
  order by requested_at
  for update skip locked
  limit 1;

  if v_id is null then
    return;
  end if;

  return query
  update public.ingestion_jobs
  set status = 'running',
      started_at = coalesce(started_at, now()),
      heartbeat_at = now(),
      worker_id = p_worker_id,
      message = 'Job claimed by Railway worker'
  where id = v_id
  returning *;
end;
$$;

-- Refresh exact candle bounds/count at sensible checkpoints rather than counting on every dashboard load.
create or replace function public.refresh_ingestion_state(p_symbol text, p_interval text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count bigint;
  v_min timestamptz;
  v_max timestamptz;
begin
  select count(*), min(candle_time), max(candle_time)
  into v_count, v_min, v_max
  from public.market_candles
  where symbol = p_symbol and interval = p_interval;

  insert into public.ingestion_state (
    symbol, interval, rows_in_database, oldest_stored, latest_stored, updated_at
  ) values (
    p_symbol, p_interval, v_count, v_min, v_max, now()
  )
  on conflict (symbol, interval) do update set
    rows_in_database = excluded.rows_in_database,
    oldest_stored = excluded.oldest_stored,
    latest_stored = excluded.latest_stored,
    updated_at = now();
end;
$$;

create or replace function public.scan_market_gaps(
  p_symbol text,
  p_interval text,
  p_interval_seconds integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total integer;
  v_review integer;
begin
  delete from public.data_gaps
  where symbol = p_symbol and interval = p_interval and classification <> 'repaired';

  with ordered as (
    select
      candle_time,
      lead(candle_time) over (order by candle_time) as next_time
    from public.market_candles
    where symbol = p_symbol and interval = p_interval
  ), gaps as (
    select
      candle_time as gap_start,
      next_time as gap_end,
      greatest(
        floor(extract(epoch from (next_time - candle_time)) / p_interval_seconds)::integer - 1,
        1
      ) as missing_bars,
      case
        when extract(epoch from (next_time - candle_time)) >= 21600 then 'expected_market_closure'
        when extract(isodow from candle_time at time zone 'UTC') in (5,6,7)
          and extract(isodow from next_time at time zone 'UTC') in (1,2,7)
          then 'expected_market_closure'
        else 'review'
      end as classification
    from ordered
    where next_time is not null
      and extract(epoch from (next_time - candle_time)) > (p_interval_seconds * 1.5)
  )
  insert into public.data_gaps (
    symbol, interval, gap_start, gap_end, missing_bars, classification
  )
  select p_symbol, p_interval, gap_start, gap_end, missing_bars, classification
  from gaps
  on conflict (symbol, interval, gap_start, gap_end) do update set
    missing_bars = excluded.missing_bars,
    classification = excluded.classification,
    detected_at = now();

  select count(*), count(*) filter (where classification = 'review')
  into v_total, v_review
  from public.data_gaps
  where symbol = p_symbol and interval = p_interval;

  return jsonb_build_object('total', v_total, 'review', v_review);
end;
$$;

create or replace function public.get_market_dashboard(p_symbol text, p_interval text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'state', coalesce((
      select to_jsonb(s) from public.ingestion_state s
      where s.symbol = p_symbol and s.interval = p_interval
    ), '{}'::jsonb),
    'latest_job', coalesce((
      select to_jsonb(j) from public.ingestion_jobs j
      where j.symbol = p_symbol and j.interval = p_interval
      order by requested_at desc limit 1
    ), '{}'::jsonb),
    'latest_candle', coalesce((
      select to_jsonb(c) from public.market_candles c
      where c.symbol = p_symbol and c.interval = p_interval
      order by candle_time desc limit 1
    ), '{}'::jsonb),
    'gaps', jsonb_build_object(
      'total', (select count(*) from public.data_gaps g where g.symbol = p_symbol and g.interval = p_interval),
      'review', (select count(*) from public.data_gaps g where g.symbol = p_symbol and g.interval = p_interval and g.classification = 'review')
    ),
    'events', coalesce((
      select jsonb_agg(to_jsonb(e) order by e.created_at desc)
      from (
        select * from public.system_events
        order by created_at desc limit 12
      ) e
    ), '[]'::jsonb)
  );
$$;

