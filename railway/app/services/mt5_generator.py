def static_validate_mq5(source: str, frozen: dict[str, Any]) -> list[str]:
    issues: list[str] = []
    required = [
        "#property strict",
        "int OnInit()",
        "void OnTick()",
        "InpEnableTrading             = false",
        "EVE_RULE_HASH",
        "SourceConditionMatched",
        "CalculateFeatureSet",
        "ManageMaximumHold",
        "DailyLossGuardPassed",
        "M1",  # present in header/report context; prevents an empty template slipping through
    ]
    for token in required:
        if token not in source:
            issues.append(f"Missing required source token: {token}")
    rule_hash = str(frozen.get("rule_hash") or "")
    if rule_hash and rule_hash not in source:
        issues.append("Frozen rule hash is not embedded in the EA source")
    if source.count("{") != source.count("}"):
        issues.append("Unbalanced braces in generated MQL5 source")
    if "TODO" in source or "PLACEHOLDER" in source:
        issues.append("Generated source contains an unresolved placeholder")
    return issues


