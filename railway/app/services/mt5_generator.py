class MT5GeneratorService:
    def __init__(self, settings: Settings, repo: SupabaseRepository) -> None:
        self.settings = settings
        self.repo = repo
        self.worker_id = f"mt5-generator-{socket.gethostname()}-{uuid.uuid4().hex[:8]}"
        self._stop = asyncio.Event()
        self._wake = asyncio.Event()

    async def stop(self) -> None:
        self._stop.set()
        self._wake.set()

    async def request_wake(self) -> None:
        self._wake.set()

    async def loop(self) -> None:
        if not self.settings.mt5_generator_enabled:
            logger.info("MT5 generator is disabled")
            return
        logger.info("MT5 generator worker %s started", self.worker_id)
        try:
            await asyncio.wait_for(self._stop.wait(), timeout=self.settings.mt5_generator_startup_delay_seconds)
            return
        except asyncio.TimeoutError:
            pass

        while not self._stop.is_set():
            try:
                await self.repo.upsert_mt5_generation_state(
                    "XAU/USD", status="active", worker_id=self.worker_id,
                    heartbeat_at=utc_now().isoformat(), started_at=utc_now().isoformat(), last_error=None,
                )
                await self.repo.reset_stale_mt5_generation_jobs()
                await self._ensure_queue()
                job = await self.repo.claim_next_mt5_generation_job(self.worker_id)
                if job:
                    await self._execute(job)
                else:
                    await self._sleep(self.settings.mt5_generator_idle_seconds)
                    continue
            except asyncio.CancelledError:
                raise
            except Exception as exc:
                logger.exception("MT5 generation cycle failed")
                await self.repo.upsert_mt5_generation_state(
                    "XAU/USD", status="error", heartbeat_at=utc_now().isoformat(),
                    last_error=str(exc)[:4000], last_result="MT5 generator recovered from an error and will retry automatically.",
                )
                await self._sleep(max(60.0, self.settings.mt5_generator_idle_seconds))
            await self._sleep(self.settings.mt5_generator_job_delay_seconds)

    async def _sleep(self, seconds: float) -> None:
        self._wake.clear()
        stop_task = asyncio.create_task(self._stop.wait())
        wake_task = asyncio.create_task(self._wake.wait())
        _, pending = await asyncio.wait({stop_task, wake_task}, timeout=max(1.0, seconds), return_when=asyncio.FIRST_COMPLETED)
        for task in pending:
            task.cancel()
        await asyncio.gather(*pending, return_exceptions=True)

    async def _ensure_queue(self) -> None:
        await self.repo.refresh_mt5_generation_state("XAU/USD")
        state = await self.repo.get_mt5_generation_state("XAU/USD") or {}
        if int(number(state.get("queue_count"))) >= self.settings.mt5_generator_queue_floor:
            return
        frozen = await self.repo.list_mt5_generation_seeds("XAU/USD", limit=MAX_GENERATION_SEEDS)
        rows = []
        for item in frozen:
            rows.append({
                "generation_key": generation_key(item),
                "symbol": item.get("symbol") or "XAU/USD",
                "frozen_strategy_id": item.get("id"),
                "strategy_code": item.get("strategy_code"),
                "strategy_name": item.get("name"),
                "frozen_version": item.get("version") or "1.0",
                "rule_hash": item.get("rule_hash"),
                "priority": 95,
                "status": "queued",
            })
        if rows:
            await self.repo.upsert_mt5_generation_jobs(rows)
            await self.repo.upsert_mt5_generation_state(
                "XAU/USD", status="active", last_generation_at=utc_now().isoformat(),
                last_result=f"Queued {len(rows)} frozen strategies for automatic MT5 source generation.",
            )
        else:
            await self.repo.upsert_mt5_generation_state(
                "XAU/USD", last_result="Waiting for a frozen strategy marked Ready for MT5 Generation.",
            )
        await self.repo.refresh_mt5_generation_state("XAU/USD")

    async def _execute(self, job: dict[str, Any]) -> None:
        job_id = str(job["id"])
        frozen_id = str(job.get("frozen_strategy_id") or "")
        name = str(job.get("strategy_name") or job.get("strategy_code") or "EVE strategy")
        await self.repo.upsert_mt5_generation_state(
            "XAU/USD", status="generating", worker_id=self.worker_id, heartbeat_at=utc_now().isoformat(),
            current_job_id=job_id, current_job_name=name, last_job_started_at=utc_now().isoformat(), last_error=None,
        )
        try:
            frozen = await self.repo.get_frozen_strategy(frozen_id)
            if not frozen:
                raise RuntimeError("Frozen strategy no longer exists")
            payload = generate_package_payload(frozen)
            package = await self.repo.create_mt5_package(job, frozen, payload)
            await self.repo.complete_mt5_generation_job(
                job_id,
                package_id=package.get("id"),
                file_name=payload["file_name"],
                source_sha256=payload["source_sha256"],
                result_status="generated",
                evidence={
                    "verdict": "Generated from immutable frozen rules. Ready for MetaEditor compilation and MT5 demo forward testing.",
                    "safety": "The EA defaults to InpEnableTrading=false and must not be used on live money.",
                },
            )
            await self.repo.mark_frozen_strategy_mt5_generated(frozen_id)
            await self.repo.upsert_mt5_generation_state(
                "XAU/USD", status="active", heartbeat_at=utc_now().isoformat(), current_job_id=None,
                current_job_name=None, last_job_finished_at=utc_now().isoformat(),
                last_result=f"Generated MT5 package {payload['package_code']} from frozen rules.", last_error=None,
            )
            await self.repo.log_event(
                "success", "mt5-generator", "MT5 package generated",
                {"strategy": name, "package_id": package.get("id"), "source_sha256": payload["source_sha256"]},
            )
            await self.repo.refresh_mt5_generation_state("XAU/USD")
        except Exception as exc:
            await self.repo.fail_mt5_generation_job(job_id, str(exc))
            await self.repo.upsert_mt5_generation_state(
                "XAU/USD", status="error", heartbeat_at=utc_now().isoformat(), current_job_id=None,
                current_job_name=None, last_job_finished_at=utc_now().isoformat(), last_error=str(exc)[:4000],
                last_result=f"MT5 generation failed safely for {name}. Frozen rules were not changed.",
            )
            raise
