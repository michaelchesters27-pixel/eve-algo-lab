def build_package_zip(package: dict[str, Any]) -> bytes:
    buffer = io.BytesIO()
    files = build_package_files(package)
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in files.items():
            archive.writestr(name, content)
        checksums = "\n".join(f"{hashlib.sha256(content).hexdigest()}  {name}" for name, content in files.items()) + "\n"
        archive.writestr("SHA256SUMS.txt", checksums)
    return buffer.getvalue()


